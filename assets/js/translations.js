function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = dict[el.getAttribute('data-i18n')];
    if (v != null) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const v = dict[el.getAttribute('data-i18n-html')];
    if (v != null) el.innerHTML = v;
  });

  const btn = document.getElementById('langToggle');
  if (btn) btn.textContent = dict.lang_line;

  localStorage.setItem('lang', lang);
  restartTyping(lang);
  restartHero(lang);
}

function toggleLang() {
  applyLang(getLang() === 'en' ? 'es' : 'en');
}

let typingTimer;
function restartTyping(lang) {
  const el = document.querySelector('.typing__text');
  if (!el) return;
  clearTimeout(typingTimer);

  const words = TYPING[lang] || TYPING.en;
  let wi = 0;
  let ci = 0;
  let deleting = false;

  function step() {
    const word = words[wi];
    if (!deleting) {
      ci++;
      el.textContent = word.slice(0, ci);
      if (ci === word.length) {
        deleting = true;
        typingTimer = setTimeout(step, 1400);
        return;
      }
    } else {
      ci--;
      el.textContent = word.slice(0, ci);
      if (ci === 0) {
        deleting = false;
        wi = (wi + 1) % words.length;
      }
    }
    typingTimer = setTimeout(step, deleting ? 45 : 95);
  }
  step();
}

let heroTimer;
function restartHero(lang) {
  const l1 = document.getElementById('heroL1');
  const l2 = document.getElementById('heroL2');
  if (!l1 || !l2) return;
  clearTimeout(heroTimer);

  const titles = HERO[lang] || HERO.en;
  const HOLD = 3200;
  const MOVE = 900;
  let i = 0;

  function enter(el, html, delay) {
    el.style.transition = 'none';
    el.classList.remove('is-in', 'is-out');
    el.innerHTML = html;
    void el.offsetWidth;
    el.style.transition = '';
    el.style.transitionDelay = delay + 'ms';
    el.classList.add('is-in');
  }

  function exit(el, delay) {
    el.style.transitionDelay = delay + 'ms';
    el.classList.remove('is-in');
    el.classList.add('is-out');
  }

  function cycle() {
    enter(l1, titles[i][0], 0);
    enter(l2, titles[i][1], 120);
    heroTimer = setTimeout(() => {
      exit(l1, 0);
      exit(l2, 80);
      heroTimer = setTimeout(() => {
        i = (i + 1) % titles.length;
        cycle();
      }, MOVE + 120);
    }, HOLD);
  }
  cycle();
}

